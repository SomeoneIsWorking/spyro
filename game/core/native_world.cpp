// native_world.cpp — Spyro's world renderer (0x800258F0 RenderWorldChunks), owned natively.
//
// WHY THIS FUNCTION, AND WHY OWNERSHIP. Widescreen and 60fps both need per-primitive DEPTH for
// 2D-vs-3D discrimination (re-frontier render.own-geometry-family): the framework's 2D widen shifts
// the whole frame a second time at this port's ~2.5% depth coverage (C143) and the uncovered-margin
// strip (issue 0039) is in the same class. Depth (SZ3) is a GTE/scratchpad intermediate ONLY in
// this renderer — never written into the emitted GPU packets (C201; C215 corrects C198's final-arm
// label) — so an interpreted body cannot
// supply it; only an OWNED body can emit depth as it projects.
//
// THE SHAPE, from the corrected structural map (C215) and the recompiled body (generated/shard_3.c
// gen_func_800258F0, ~5000 instructions across 0x800258F0..0x8002A6F4):
//   Phase 1 (0x800258F0..0x800261A0): save callee-saved regs to the fixed save area kSaveArea (no
//     stack frame), load the camera view matrix into the GTE (translation nulled), then walk the
//     environment chunk list (occlusion-group table kEnvironment+8 when a0>=0, flat count-list
//     kEnvironment+0/4 when a0<0), culling each chunk by view frustum + distance (MVMVA against the
//     view matrix, radius shift thresholds vs m_LodDistance) and applying the per-chunk environment
//     geometry/colour animation (INTPL/DPCS blocks writing into chunk vertex/colour arrays).
//     Survivors are written to the work list at kWorkList+0x1C00.
//   Phase 2 (0x800261A0..0x8002A0B0): project every surviving chunk's vertices (RTPS), write
//     SXY2+SZ3 into scratchpad caches, and emit LQ direct plus HQ direct/medium/near gouraud faces
//     with NCLIP, depth/LOD, whole-face clip rejection, fog, texture-table selection, edge fillers,
//     and OT binning. This is where native DEPTH is emitted.
//   Phase 3 (0x8002A0A0..0x8002A6B0): breadth-first adaptive subdivision of oversized near GT3/GT4
//     packets. D_8006D5E4/D_8006D5C8 are child-descriptor tables; each final child chain replaces
//     its parent in the same OT slot. This is not a special-surface renderer (C215 supersedes
//     C198).
//   Epilogue: publish the pool pointer to kPoolPtr, link g_WorldOT, restore registers, return.
//
// HOW THE BODY IS PRODUCED — AND WHY IT IS NOT HAND-TRANSCRIBED. native_terrain.cpp's body
// (0x8004EBA8) was transcribed by hand and it worked: that function is small enough to hold in one
// head, and it verified byte-exact over 400 calls. This one is ~5000 instructions, and hand
// transcription was tried here and MEASURED to fail: the first 40 instructions of the attempt
// carried four defects — a delay-slot load (`s2 = m_SectorPointer`) made conditional when the
// hardware executes it on both paths, an unconditional `s5` increment written as conditional, a
// register substituted (v0 for at), and every `rec_irq_poll` dropped. None of those is visible
// until all 5000 are typed, because the differential can only run a whole body. The instrument was
// wrong for the size, not the person using it.
//
// So world_body.inc is GENERATED by tools/transcribe.py, which renders the recompiled body through
// a BIJECTION — register numbers to MIPS names, lui/addiu address pairs to one named constant,
// offsets to signed form — and nothing else. `transcribe.py check` re-derives the generated source
// from the emitted file and fails on any divergence; it runs in the gate, so the body stays exact
// as the substrate is regenerated. That is a stronger guarantee than a hand transcription can give,
// because it holds by construction rather than by review, and it is what makes the depth hooks
// safe to add: a hook is an annotation keyed to a guest address (world_annotations.json), injected
// at emit time and stripped before the check compares, with its count printed so an annotation can
// never silently mask a divergence.
//
// BYTE-EXACT IS THE ADMISSION REQUIREMENT, not a stretch goal. ndiff snapshots RAM, the scratchpad,
// every GPR and the COP2 register file, runs this body, rewinds, runs the recompiled body, and
// compares. An identity probe proved the differential CAN validate a function of this shape (C202,
// 20/20 exact) and the depth oracle measured the ground's real SZ3 range + per-face OT bins (C201).
